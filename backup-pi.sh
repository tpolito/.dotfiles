#!/usr/bin/env bash
# Back up the non-sensitive parts of ~/.pi into ./pi within this dotfiles repo.
#
# Included:
#   .pi/mcp.jsonc                          (MCP config — currently empty {})
#   .pi/trust.json                         (trusted project paths)
#   .pi/agent/settings.json                 (provider/model/theme/packages — NO secrets)
#   .pi/agent/themes/*.json                 (custom themes)
#   .pi/agent/skills/**                     (SKILL.md folders, excluding node_modules)
#   .pi/agent/extensions/*.ts               (your authored single-file extensions)
#   .pi/agent/extensions/{web-tools,save-md} (subdir extensions, source only)
#
# Excluded (regenerable or secret):
#   .pi/agent/auth.json          — API keys
#   .pi/agent/sessions/          — per-project session history
#   .pi/agent/npm/               — installed npm packages (reinstall via `pi install`)
#   .pi/agent/git/               — cloned git packages (reinstall via `pi install`)
#   **/node_modules/            — anywhere
#   **/package-lock.json         — in subdir extensions (regenerated by npm install)
#
# Usage:
#   ./backup-pi.sh            # back up into ./pi
#   ./backup-pi.sh --dry-run  # show what would be copied without writing

set -euo pipefail

SRC="${PI_HOME:-$HOME/.pi}"
DEST="$(cd "$(dirname "$0")" && pwd)/pi"

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

if [[ ! -d "$SRC" ]]; then
  echo "error: pi config not found at $SRC" >&2
  exit 1
fi

echo "Backing up $SRC -> $DEST"
if [[ $DRY_RUN -eq 1 ]]; then
  echo "(dry run — no files will be written)"
  run() { echo "  $*"; }
else
  run() { "$@"; }
fi

# Start clean so deleted files don't linger in the repo.
if [[ $DRY_RUN -eq 0 ]]; then
  rm -rf "$DEST"
fi
run mkdir -p "$DEST/agent/extensions" "$DEST/agent/themes"

cp_file() {
  # cp_file <src> <dest>
  if [[ -f "$1" ]]; then
    run cp "$1" "$2"
  else
    echo "  skip (missing): $1"
  fi
}

# Top-level configs
cp_file "$SRC/mcp.jsonc"            "$DEST/mcp.jsonc"
cp_file "$SRC/trust.json"           "$DEST/trust.json"

# Settings (provider/model/theme/packages — no secrets)
cp_file "$SRC/agent/settings.json"  "$DEST/agent/settings.json"

# Themes
if [[ -d "$SRC/agent/themes" ]]; then
  for f in "$SRC"/agent/themes/*.json; do
    [[ -e "$f" ]] && cp_file "$f" "$DEST/agent/themes/$(basename "$f")"
  done
fi

# Skills — everything except node_modules
if [[ -d "$SRC/agent/skills" ]]; then
  run rsync -a --delete --exclude='node_modules' \
    "$SRC/agent/skills/" "$DEST/agent/skills/"
fi

# Single-file authored extensions: *.ts at the top level of extensions/
shopt -s nullglob
for f in "$SRC"/agent/extensions/*.ts; do
  cp_file "$f" "$DEST/agent/extensions/$(basename "$f")"
done
shopt -u nullglob

# Subdir-style extensions — source only, no node_modules or lock files.
for d in web-tools save-md; do
  if [[ -d "$SRC/agent/extensions/$d" ]]; then
    run rsync -a --delete \
      --exclude='node_modules' --exclude='package-lock.json' \
      "$SRC/agent/extensions/$d/" "$DEST/agent/extensions/$d/"
  fi
done

# Final sanity guard: never let secrets or junk slip in.
LEAKS=$(find "$DEST" \
  \( -name auth.json -o -path '*/sessions/*' -o -path '*/npm/*' -o -path '*/git/*' -o -path '*/node_modules/*' \) \
  -print 2>/dev/null || true)
if [[ -n "$LEAKS" ]]; then
  echo "error: leaked files found in backup:" >&2
  echo "$LEAKS" >&2
  exit 1
fi

echo "done."
if [[ $DRY_RUN -eq 0 ]]; then
  echo "Review with: git -C \"$DEST/..\" status pi"
  echo "Commit with: git -C \"$DEST/..\" add pi && git -C \"$DEST/..\" commit -m \"backup pi config\""
fi